#include "scrypt/cipher/aes256.h"
#include <assert.h>
#include <stdio.h>
#include <string.h>

int main(void) {
    /* FIPS 197 Appendix C.3 test vector */
    const uint8_t key[32] = {
        0x00, 0x01, 0x02, 0x03, 0x04, 0x05, 0x06, 0x07,
        0x08, 0x09, 0x0a, 0x0b, 0x0c, 0x0d, 0x0e, 0x0f,
        0x10, 0x11, 0x12, 0x13, 0x14, 0x15, 0x16, 0x17,
        0x18, 0x19, 0x1a, 0x1b, 0x1c, 0x1d, 0x1e, 0x1f
    };
    const uint8_t plaintext[16] = {
        0x00, 0x11, 0x22, 0x33, 0x44, 0x55, 0x66, 0x77,
        0x88, 0x99, 0xaa, 0xbb, 0xcc, 0xdd, 0xee, 0xff
    };
    const uint8_t expected_ct[16] = {
        0x8e, 0xa2, 0xb7, 0xca, 0x51, 0x67, 0x45, 0xbf,
        0xea, 0xfc, 0x49, 0x90, 0x4b, 0x49, 0x60, 0x89
    };

    uint8_t ct[16] = {0};
    uint8_t pt[16] = {0};

    scrypt_aes256_ctx ctx;
    scrypt_aes256_init(&ctx, key);
    scrypt_aes256_encrypt_block(&ctx, plaintext, ct);
    scrypt_aes256_decrypt_block(&ctx, ct, pt);
    scrypt_aes256_wipe(&ctx);

    assert(memcmp(ct, expected_ct, sizeof(expected_ct)) == 0);
    assert(memcmp(pt, plaintext, sizeof(plaintext)) == 0);

    printf("AES-256 block encrypt/decrypt KAT passed.\n");
    return 0;
}
