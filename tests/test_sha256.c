#include "scrypt/hash/sha256.h"
#include <assert.h>
#include <stdio.h>
#include <string.h>

int main(void) {
    /* Test vector 1: "abc" */
    const char *msg1 = "abc";
    const uint8_t exp1[32] = {
        0xba, 0x78, 0x16, 0xbf, 0x8f, 0x01, 0xcf, 0xea,
        0x41, 0x41, 0x40, 0xde, 0x5d, 0xae, 0x22, 0x23,
        0xb0, 0x03, 0x61, 0xa3, 0x96, 0x17, 0x7a, 0x9c,
        0xb4, 0x10, 0xff, 0x61, 0xf2, 0x00, 0x15, 0xad
    };

    uint8_t digest1[32];
    scrypt_sha256(msg1, strlen(msg1), digest1);
    assert(memcmp(digest1, exp1, sizeof(exp1)) == 0);

    /* Test vector 2: empty string "" */
    const uint8_t exp_empty[32] = {
        0xe3, 0xb0, 0xc4, 0x42, 0x98, 0xfc, 0x1c, 0x14,
        0x9a, 0xfb, 0xf4, 0xc8, 0x99, 0x6f, 0xb9, 0x24,
        0x27, 0xae, 0x41, 0xe4, 0x64, 0x9b, 0x93, 0x4c,
        0xa4, 0x95, 0x99, 0x1b, 0x78, 0x52, 0xb8, 0x55
    };

    uint8_t digest_empty[32];
    scrypt_sha256("", 0, digest_empty);
    assert(memcmp(digest_empty, exp_empty, sizeof(exp_empty)) == 0);

    /* Test vector 3: multi-part streaming "abcdbcdecdefdefgefghfghighijhijkijkljklmklmnlmnomnopnopq" */
    const char *msg3 = "abcdbcdecdefdefgefghfghighijhijkijkljklmklmnlmnomnopnopq";
    const uint8_t exp3[32] = {
        0x24, 0x8d, 0x6a, 0x61, 0xd2, 0x06, 0x38, 0xb8,
        0xe5, 0xc0, 0x26, 0x93, 0x0c, 0x3e, 0x60, 0x39,
        0xa3, 0x3c, 0xe4, 0x59, 0x64, 0xff, 0x21, 0x67,
        0xf6, 0xec, 0xed, 0xd4, 0x19, 0xdb, 0x06, 0xc1
    };

    scrypt_sha256_ctx ctx;
    scrypt_sha256_init(&ctx);
    scrypt_sha256_update(&ctx, msg3, 20);
    scrypt_sha256_update(&ctx, msg3 + 20, strlen(msg3) - 20);
    uint8_t digest3[32];
    scrypt_sha256_final(&ctx, digest3);
    assert(memcmp(digest3, exp3, sizeof(exp3)) == 0);

    printf("SHA-256 standard and streaming KATs passed.\n");
    return 0;
}
